// Generates supabase/seed.sql and apps/pwa/public/demo/*.svg from the shared
// demo profile generator, so the mock backend and a real Supabase project show
// the same 70 people.
//
//   pnpm gen:seed-sql [--lat 45.5017 --lng -73.5673]
import { mkdirSync, writeFileSync } from 'node:fs';
import { dirname, join } from 'node:path';
import { fileURLToPath } from 'node:url';
import { demoPhotoSvg, generateDemoProfiles } from '../shared/content/src/demoProfiles.ts';
import { demoUuid, offsetPoint } from '../shared/content/src/demoIds.ts';

const root = join(dirname(fileURLToPath(import.meta.url)), '..');
const arg = (name: string, fallback: number) => {
  const i = process.argv.indexOf(`--${name}`);
  return i > 0 ? Number(process.argv[i + 1]) : fallback;
};
const center = { lat: arg('lat', 45.5017), lng: arg('lng', -73.5673) };

const q = (v: unknown): string => {
  if (v === null || v === undefined) return 'null';
  if (typeof v === 'number' || typeof v === 'boolean') return String(v);
  return `'${String(v).replace(/'/g, "''")}'`;
};
const arr = (xs: readonly (string | number)[]) =>
  `array[${xs.map((x) => (typeof x === 'number' ? x : q(x))).join(',')}]${typeof xs[0] === 'number' ? '::smallint[]' : '::text[]'}`;
const json = (v: unknown) => `${q(JSON.stringify(v))}::jsonb`;

const people = generateDemoProfiles();
const demoDir = join(root, 'apps/pwa/public/demo');
mkdirSync(demoDir, { recursive: true });

const lines: string[] = [
  '-- GENERATED by scripts/gen-seed-sql.ts. Do not edit by hand.',
  `-- 70 demo profiles centred on ${center.lat}, ${center.lng}. Photos are served by the PWA at /demo/*.svg.`,
  '-- Applied by `supabase db reset` (local) or manually in the SQL editor for a demo project.',
  'begin;',
  '',
];

for (const [n, p] of people.entries()) {
  const id = demoUuid(n + 1);
  const loc = offsetPoint(center, p.offset_km);
  const email = `${p.id}@demo.linky.app`;
  lines.push(`-- ${p.name} (${p.id})`);
  lines.push(
    `insert into auth.users (instance_id, id, aud, role, email, encrypted_password, email_confirmed_at, created_at, updated_at, raw_app_meta_data, raw_user_meta_data) values ('00000000-0000-0000-0000-000000000000', ${q(id)}, 'authenticated', 'authenticated', ${q(email)}, '', now(), now(), now(), '{"provider":"email","providers":["email"]}', '{"demo":true}') on conflict (id) do nothing;`,
  );
  lines.push(
    `insert into public.profiles (id, name, birthdate, gender, pronouns, orientation, city, location, height_cm, verified, verified_at, onboarding_complete, last_active_at) values (${q(id)}, ${q(p.name)}, ${q(p.birthdate)}, ${q(p.gender)}, ${q(p.pronouns)}, ${q(p.orientation)}, ${q(p.city)}, extensions.st_setsrid(extensions.st_makepoint(${loc.lng.toFixed(4)}, ${loc.lat.toFixed(4)}), 4326)::extensions.geography, ${q(p.height_cm)}, ${p.verified}, ${p.verified ? 'now()' : 'null'}, true, now() - interval '${p.last_active_hours} hours') on conflict (id) do nothing;`,
  );
  const photoCount = 1 + p.scenes.length;
  for (let i = 0; i < photoCount; i++) {
    const file = `${p.id}-${i}.svg`;
    writeFileSync(join(demoDir, file), demoPhotoSvg(p, i));
    lines.push(
      `insert into public.photos (id, profile_id, r2_key, url, position, nsfw_score) values (${q(demoUuid(n + 1, 100 + i))}, ${q(id)}, ${q('demo/' + file)}, ${q('/demo/' + file)}, ${i}, 0);`,
    );
  }
  p.prompts.forEach((pr, i) =>
    lines.push(
      `insert into public.prompt_answers (id, profile_id, prompt, answer, position) values (${q(demoUuid(n + 1, 200 + i))}, ${q(id)}, ${q(pr.prompt)}, ${q(pr.answer)}, ${i});`,
    ),
  );
  const pe = p.personality;
  lines.push(
    `insert into public.personality (profile_id, type, e_i, s_n, t_f, j_p) values (${q(id)}, ${q(pe.type)}, ${pe.e_i}, ${pe.s_n}, ${pe.t_f}, ${pe.j_p});`,
  );
  lines.push(
    `insert into public.love_language (profile_id, receive, give) values (${q(id)}, ${arr(p.love_language.receive)}, ${arr(p.love_language.give)});`,
  );
  for (const [key, s] of Object.entries(p.attributes)) {
    if (!s) continue;
    lines.push(
      `insert into public.attributes (profile_id, key, value, visible, is_dealbreaker) values (${q(id)}, ${q(key)}, ${json(s.value)}, ${s.visible}, ${s.is_dealbreaker});`,
    );
  }
  lines.push(
    `insert into public.preferences (profile_id, age_min, age_max, distance_km, genders_wanted) values (${q(id)}, ${p.age_min}, ${p.age_max}, ${q(p.distance_km)}, ${arr(p.seeking)});`,
  );
  if (p.kinks) {
    lines.push(
      `insert into public.kinks (profile_id, opted_in, tags, visibility_level) values (${q(id)}, true, ${arr(p.kinks.tags)}, ${q(p.kinks.visibility_level)});`,
    );
  }
  for (const h of p.handles) {
    lines.push(
      `insert into public.messenger_handles (profile_id, app, handle, preferred) values (${q(id)}, ${q(h.app)}, ${q(h.handle)}, ${h.preferred});`,
    );
  }
  lines.push('');
}

// Demo-only bots: some demo profiles like you back and accept Connect automatically,
// so one tester can walk the full flow. Not part of the migrations on purpose.
lines.push(
  '-- Demo bots (demo environments only)',
  'create table if not exists public.demo_bots (profile_id uuid primary key references public.profiles (id) on delete cascade, likes_back boolean not null);',
  'alter table public.demo_bots enable row level security;',
  `insert into public.demo_bots (profile_id, likes_back) values ${people
    .map((p, n) => `(${q(demoUuid(n + 1))}, ${p.bot.likes_back})`)
    .join(', ')} on conflict do nothing;`,
  `create or replace function public.demo_bot_like_back() returns trigger
language plpgsql security definer set search_path = public as $$
declare target_id uuid; target_type text;
begin
  if exists (select 1 from demo_bots where profile_id = new.to_id and likes_back)
     and not exists (select 1 from likes where from_id = new.to_id and to_id = new.from_id) then
    select id, 'photo' into target_id, target_type from photos where profile_id = new.from_id order by position limit 1;
    if target_id is not null then
      insert into likes (from_id, to_id, target_type, target_id, comment) values (new.to_id, new.from_id, target_type, target_id, null);
      insert into matches (user_a, user_b) values (least(new.from_id, new.to_id), greatest(new.from_id, new.to_id)) on conflict do nothing;
    end if;
  end if;
  return new;
end $$;`,
  'drop trigger if exists demo_bot_like_back on public.likes;',
  'create trigger demo_bot_like_back after insert on public.likes for each row execute function public.demo_bot_like_back();',
  `create or replace function public.demo_bot_connect() returns trigger
language plpgsql security definer set search_path = public as $$
begin
  if new.connect_a and not new.connect_b and exists (select 1 from demo_bots where profile_id = new.user_b) then new.connect_b := true; end if;
  if new.connect_b and not new.connect_a and exists (select 1 from demo_bots where profile_id = new.user_a) then new.connect_a := true; end if;
  return new;
end $$;`,
  'drop trigger if exists demo_bot_connect on public.matches;',
  'create trigger demo_bot_connect before update on public.matches for each row execute function public.demo_bot_connect();',
  '',
  'commit;',
  '',
);

writeFileSync(join(root, 'supabase/seed.sql'), lines.join('\n'));
console.log(`Wrote supabase/seed.sql (${people.length} profiles) and ${demoDir}`);
